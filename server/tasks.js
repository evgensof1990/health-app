// AI tasks for the growth, self and style sections. Each task has a schema for the structured
// reply, a short role prompt and a function that turns the request (plus stored state) into text.
import { z } from 'zod';

const ABOUT = 'Пользователь — взрослый мужчина из России. Тон дружеский, на «ты», без пафоса, морализаторства и мотивационных штампов. Конкретика вместо общих слов. Простой текст без markdown.';

const profileLine = (state) => {
  const p = state.profile;
  return p ? `Профиль: ${p.sex === 'f' ? 'женщина' : 'мужчина'}, ${p.age} лет, рост ${p.height} см, вес ${p.weight} кг.` : '';
};

export const TASKS = {
  // ---------- growth ----------
  books: {
    system: `Ты книжный советчик для человека, который давно толком не читал и хочет мягко вернуться к чтению. ${ABOUT}
Подбирай книги, которые затягивают с первых страниц: живой язык, понятная польза или сильный сюжет, разумный объём (лучше до 350 страниц). Только реально существующие книги, изданные на русском; автора и название пиши как в русском издании. Не повторяй книги, которые уже прочитаны или на полке. Для каждой книги — почему именно ему, и с чего начать, чтобы втянуться.`,
    schema: z.object({
      books: z.array(
        z.object({
          title: z.string(),
          author: z.string(),
          pages: z.number().describe('Примерный объём в страницах'),
          why: z.string().describe('1–2 предложения: почему это зайдёт именно ему'),
          start: z.string().describe('Как начать: сколько читать в день, на что обратить внимание'),
        })
      ),
    }),
    prompt: (input, state) => {
      const g = state.sections.growth;
      const shelf = g.books.map((b) => `${b.title} — ${b.author} (${b.status === 'done' ? 'прочитано' : b.status === 'dropped' ? 'бросил' : 'на полке'}${b.rating ? `, оценка ${b.rating}/5` : ''})`);
      return `Интересы и пожелания: ${input.wish || 'не указаны, предложи разнообразно: нон-фикшн про жизнь и мышление, одну художественную, одну про здоровье или привычки'}.
${shelf.length ? 'Уже на полке или прочитано:\n' + shelf.join('\n') : 'Полка пока пустая.'}
Предложи 5 книг.`;
    },
  },

  wheel: {
    system: `Ты коуч по балансу жизни. ${ABOUT}
На входе — колесо баланса: оценки сфер жизни от 1 до 10, иногда с прошлой оценкой для сравнения. Найди 2–3 сферы, где маленький шаг даст больше всего, и для каждой предложи одно конкретное действие на ближайшую неделю, которое занимает не больше 15–30 минут и которое легко проверить (сделал / не сделал). Не трогай сферы, где всё хорошо, но отметь рост, если он есть.`,
    schema: z.object({
      summary: z.string().describe('2–3 предложения: общая картина и что изменилось'),
      steps: z.array(z.object({ area: z.string(), action: z.string().describe('Одно конкретное действие на неделю') })),
    }),
    prompt: (input) => {
      const line = (s) => Object.entries(s).map(([k, v]) => `${k}: ${v}`).join(', ');
      return `Сейчас: ${line(input.scores)}.${input.prev ? `\nПрошлый раз (${input.prevDate}): ${line(input.prev)}.` : ''}${input.note ? `\nКомментарий: ${input.note}` : ''}`;
    },
  },

  // ---------- self ----------
  reframe: {
    system: `Ты помогаешь работать с самооценкой методами когнитивно-поведенческой терапии. ${ABOUT}
На входе — мысль или ситуация, которая задевает. Мягко назови искажение мышления, если оно есть (катастрофизация, чтение мыслей, обесценивание, «всё или ничего», навешивание ярлыков, долженствование и т. п.), предложи более реалистичный взгляд — не розовые очки, а честную и справедливую оценку, как сказал бы умный друг. И одно маленькое действие. Если в тексте есть признаки кризиса или мысли о самоповреждении, мягко посоветуй обратиться к специалисту или на линию помощи.`,
    schema: z.object({
      distortion: z.string().nullable().describe('Название искажения и одно предложение, как оно проявилось, или null'),
      reframe: z.string().describe('Более реалистичный взгляд, 2–4 предложения'),
      action: z.string().describe('Одно маленькое действие на сегодня'),
    }),
    prompt: (input) => `Мысль или ситуация: ${input.thought}`,
  },

  jokeTask: {
    system: `Ты тренер по импровизации и остроумию. ${ABOUT}
Дай одно короткое упражнение на юмор: жизненную ситуацию или реплику собеседника, на которую нужно остроумно ответить, и подсказку по технике (неожиданный поворот, преувеличение, буквальное понимание, самоирония, ассоциация, «правило трёх», наблюдение). Ситуации — из обычной жизни взрослого: работа, семья, друзья, сервисы, быт. Без пошлости и злых тем.`,
    schema: z.object({
      situation: z.string().describe('Ситуация или реплика, 1–3 предложения'),
      technique: z.string().describe('Название техники'),
      hint: z.string().describe('Как применить технику здесь, одно предложение, без готового ответа'),
    }),
    prompt: (input, state) => {
      const recent = state.sections.self.jokes.slice(-8).map((j) => j.situation);
      return `Придумай новое упражнение. Уровень: ${input.level || 'средний'}.${input.technique ? ` Техника: ${input.technique}.` : ''}${recent.length ? '\nНе повторяй эти ситуации:\n' + recent.join('\n') : ''}`;
    },
  },

  jokeReview: {
    system: `Ты тренер по остроумию. ${ABOUT}
Оцени ответ пользователя на упражнение честно, но поддерживающе: что сработало, что можно усилить. Покажи 2 улучшенные версии его же шутки (сохрани его идею) и 1 вариант с другим ходом. Шкала 1–10, где 5 — «улыбнутся из вежливости», 7 — «засмеются», 9 — «будут пересказывать».`,
    schema: z.object({
      score: z.number(),
      works: z.string().describe('Что сработало, 1–2 предложения'),
      improve: z.string().describe('Что усилить, 1–2 предложения'),
      variants: z.array(z.string()).describe('3 варианта'),
    }),
    prompt: (input) => `Упражнение: ${input.situation}\nТехника: ${input.technique}\nОтвет пользователя: ${input.answer}`,
  },

  // ---------- style ----------
  styleGuide: {
    system: `Ты стилист-имиджмейкер для мужчин. ${ABOUT}
Составь личный гайд по стилю: исходи из образа жизни, телосложения, бюджета и того, что человек хочет транслировать. Цвета — конкретные (не «пастельные», а «серо-синий, тёмно-оливковый, песочный»). Базовая капсула — 10–14 вещей, из которых собирается большинство образов; указывай посадку, ткань, цвет. Приоритет покупки: 1 — купить первым. Учитывай российский климат и бюджет. Правила — практичные, например про длину брюк, посадку плеч, сочетание обуви и ремня.`,
    schema: z.object({
      summary: z.string().describe('Суть стиля в 2–3 предложениях'),
      colors: z.array(z.string()).describe('5–8 базовых и акцентных цветов'),
      avoid: z.array(z.string()).describe('Чего избегать, 3–5 пунктов'),
      capsule: z.array(z.object({ item: z.string(), why: z.string(), priority: z.number().describe('1–3') })),
      rules: z.array(z.string()).describe('5–8 практичных правил'),
    }),
    prompt: (input, state) => {
      const s = input.profile;
      return `${profileLine(state)}
Телосложение: ${s.build || 'не указано'}.
Образ жизни и где бывает: ${s.life || 'не указано'}.
Что хочет транслировать: ${s.image || 'не указано'}.
Бюджет на одежду в месяц: ${s.budget || 'не указан'}.
Что нравится / не нравится: ${s.likes || 'не указано'}.
${state.sections.style.items.length ? 'Уже есть в гардеробе:\n' + state.sections.style.items.map((i) => `- ${i.name} (${i.color})`).join('\n') : ''}`;
    },
  },

  styleItem: {
    image: true,
    system: `Ты стилист. ${ABOUT}
На фото — вещь из гардероба (иногда на человеке). Определи, что это, цвет и стиль, оцени состояние и посадку, если видно, и реши: оставить, носить с оговорками или заменить. Учитывай личный гайд пользователя, если он есть.`,
    schema: z.object({
      name: z.string().describe('Короткое название: «Тёмно-синий шерстяной пиджак»'),
      category: z.enum(['top', 'outer', 'bottom', 'shoes', 'accessory', 'other']).describe('top — футболки, рубашки, свитеры; outer — куртки, пальто, пиджаки'),
      color: z.string(),
      season: z.array(z.enum(['лето', 'межсезонье', 'зима'])),
      formality: z.enum(['спорт', 'повседневное', 'смарт-кэжуал', 'деловое']),
      verdict: z.enum(['keep', 'ok', 'replace']),
      note: z.string().describe('Почему такой вердикт и с чем сочетать, 1–3 предложения'),
    }),
    prompt: (input, state) => {
      const g = state.sections.style.guide;
      return `${g ? `Личный гайд: ${g.summary} Цвета: ${g.colors.join(', ')}.` : 'Личного гайда пока нет.'}${input.note ? `\nКомментарий пользователя: ${input.note}` : ''}\nОцени вещь на фото.`;
    },
  },

  outfit: {
    system: `Ты стилист. ${ABOUT}
Собери 1–2 образа из вещей гардероба пользователя под повод и погоду. Используй только вещи из списка (по их id). Если для хорошего образа чего-то не хватает, скажи, что докупить.`,
    schema: z.object({
      looks: z.array(z.object({ title: z.string(), itemIds: z.array(z.string()), why: z.string() })),
      missing: z.string().nullable().describe('Чего не хватает в гардеробе для этого повода, или null'),
    }),
    prompt: (input, state) => {
      const items = state.sections.style.items.filter((i) => i.verdict !== 'replace');
      return `Повод: ${input.occasion}.${input.weather ? ` Погода: ${input.weather}.` : ''}
Гардероб:
${items.map((i) => `${i.id}: ${i.name}, ${i.color}, ${i.formality}, сезон: ${(i.season || []).join('/')}`).join('\n') || '(пусто)'}`;
    },
  },
};
